"""
Run every deterministic experiment and write its output to `results/`.

Findings documents quote numbers. Those numbers should be reproducible by
one command and the artefact should be in the repository, otherwise a
reader has to take them on trust.

The real model experiment is excluded because it needs an API key and a
model identifier, and its results depend on which model was used.
"""

from __future__ import annotations

import importlib
import io
import json
from contextlib import redirect_stdout
from pathlib import Path


EXPERIMENTS = (
    "prompt_injection_e2e",
    "contextual_authorization_ablation",
    "adaptive_bypass_eval",
    "data_flow_composition_eval",
    "transformation_bypass_eval",
    "lineage_propagation_eval",
)

ROOT = Path(__file__).resolve().parents[1]


def _parse(text: str):
    """Read one or more JSON documents printed by an experiment."""

    decoder = json.JSONDecoder()
    documents = []
    index = 0

    while index < len(text):
        while index < len(text) and text[index].isspace():
            index += 1

        if index >= len(text):
            break

        try:
            document, index = decoder.raw_decode(text, index)
        except json.JSONDecodeError:
            # Trailing human-readable output after the JSON payload.
            break

        documents.append(document)

    if not documents:
        raise ValueError("experiment produced no JSON output")

    if len(documents) == 1:
        return documents[0]

    return documents


def main() -> None:
    results_dir = ROOT / "results"
    results_dir.mkdir(exist_ok=True)

    index: dict[str, str] = {}

    for name in EXPERIMENTS:
        module = importlib.import_module(f"experiments.{name}")
        buffer = io.StringIO()

        with redirect_stdout(buffer):
            module.main()

        payload = _parse(buffer.getvalue())
        path = results_dir / f"{name}.json"
        path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
        index[name] = f"python -m experiments.{name}"
        print(f"wrote {path.relative_to(ROOT)}")

    from evals.runner import run

    evaluation = run()
    index["benchmark"] = "python -m evals.runner"
    print(f"wrote {evaluation.relative_to(ROOT)}")

    (results_dir / "INDEX.json").write_text(
        json.dumps(
            {
                "commands": index,
                "note": (
                    "every file here is regenerated by the command listed "
                    "against it; the real model experiment is not included "
                    "because it requires an API key and a named model"
                ),
            },
            indent=2,
        ),
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
